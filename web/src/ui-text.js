export function uiMessage(value) {
  if (typeof value !== "string") return value;
  if (messages.has(value)) return messages.get(value);
  const required = /^([^\s]+) 需要 ([A-Za-z][A-Za-z0-9]*) 参数。$/.exec(value);
  if (required) return `${required[1]} requires a ${required[2]} parameter.`;
  // 插值只替换应用说明，路径、引用名与原始输出保持原文。
  const dynamic = [
    [/^文件过大（(.+)）。这里显示前 (.+) 的只读预览。$/, (m) => `Large file (${m[1].replace(/字节/g, "bytes")}). Showing the first ${m[2].replace(/字节/g, "bytes")} as a read-only preview.`],
    [/^([0-9,]+) 字节$/, (m) => `${m[1]} bytes`],
    [/^文件 (.+) 已不在 Changes 中，请刷新后重新选择。$/, (m) => `File ${m[1]} is no longer in Changes. Refresh and select it again.`],
    [/^提交已完成，但无法刷新仓库状态：([\s\S]+)$/, (m) => `Commit completed, but repository status could not be refreshed: ${uiMessage(m[1])}`],
    [/^Git (.+) 低于最低支持版本 (.+)，Git 模块已禁用。$/, (m) => `Git ${m[1]} is older than the required ${m[2]}; Git is disabled.`],
    [/^分支 (.+) 没有配置跟踪的远端分支。$/, (m) => `Branch ${m[1]} has no upstream branch.`],
    [/^无法从跟踪引用 (.+) 解析远端与远端分支。$/, (m) => `Cannot resolve the remote and branch from ${m[1]}.`],
    [/^(.+)无效。$/, (m) => messages.has(m[1]) ? `Invalid ${messages.get(m[1])}.` : value],
    [/^Windows 回收站操作失败，错误码 (.+)。$/, (m) => `Windows Recycle Bin operation failed (code ${m[1]}).`],
    [/^未找到已配置的 (.+)，终端没有启动，也没有切换到其他 Shell。$/, (m) => `Configured ${m[1]} was not found; the terminal did not start and no alternative shell was used.`],
    [/^未知的操作会话动作：(.+)。$/, (m) => `Unknown operation session action: ${m[1]}.`],
    [/^未知的冲突侧：(.+)。$/, (m) => `Unknown conflict side: ${m[1]}.`],
    [/^未知的(.+)动作：(.+?)(?:。)?$/, (m) => `Unknown ${messages.get(m[1]) || m[1]} action: ${m[2]}.`],
    [/^路径越出工作区：(.+)$/, (m) => `Path is outside the workspace: ${m[1]}`],
    [/^git\/history 的 (.+) 参数不是有效的时间。$/, (m) => `Invalid time value for git/history ${m[1]}.`],
  ];
  for (const [pattern, format] of dynamic) {
    const match = pattern.exec(value);
    if (match) return format(match);
  }
  for (const [source, target] of [
    ["内部错误：", "Internal error: "], ["未知的宿主方法：", "Unknown host method: "],
    ["目标目录不存在：", "Destination directory does not exist: "],
    ["Worktree 已锁定：", "Worktree is locked: "],
    ["本地引用不存在：", "Local reference does not exist: "],
    ["无法启动 ", "Cannot start "],
    ["当前分支 · ", "Current branch · "], ["合入内容 · ", "Incoming changes · "],
  ]) {
    if (value.startsWith(source)) return target + value.slice(source.length);
  }
  return value;
}

// 只对说明字段做不可变转换；没有变化的对象保留原身份，避免复制大文档载荷。
export function uiPayload(value, method, key = "") {
  if (typeof value === "string") {
    return ["reason", "notice", "error", "yoursLabel", "theirsLabel", "lineEndings", "typeName"].includes(key)
      || (method === "document/read" && key === "message") ? uiMessage(value) : value;
  }
  if (value === null || typeof value !== "object") return value;
  let changed = false;
  const result = Array.isArray(value) ? [] : {};
  for (const [name, child] of Object.entries(value)) {
    const next = ["rows", "lines", "commits", "files", "data", "output"].includes(name)
      ? child : uiPayload(child, method, name);
    result[name] = next;
    if (next !== child) changed = true;
  }
  return changed ? result : value;
}
