// 设置、Diff局部菜单、应用内日历和普通菜单的实际场景验证。
const assert=require('node:assert/strict');
module.exports=async function verifySettingsDiff({openScene,check}) {
  for(const theme of ['light','dark']){
    const scene=await openScene(`scene=git-history&theme=${theme}&ui-font-size=12`);
    const page=scene.page;
    try{
      await page.setViewportSize({width:1640,height:985});
      await page.locator('.titlebar [aria-label="Settings"]').click();
      await page.waitForSelector('.font-family-select');
      assert.equal(await page.locator('.settings-page h2').count(),0);
      assert.equal(await page.locator('.settings-breadcrumbs').innerText(),'Appearance & Behavior\nAppearance');
      const band=await page.locator('.settings-nav .selected').evaluate(node=>({left:node.getBoundingClientRect().left-node.parentElement.getBoundingClientRect().left,width:node.getBoundingClientRect().width,parent:node.parentElement.clientWidth,radius:getComputedStyle(node).borderRadius}));
      assert.deepEqual(band,{left:0,width:band.parent,parent:band.parent,radius:'0px'});
      await page.locator('[data-setting="textFontFamily"]').selectOption('Tahoma');
      await page.locator('[data-settings-page="file-view"]').click();
      await page.locator('[data-setting="monospaceFontFamily"]').selectOption('Courier New');
      await page.locator('[data-settings-nav="back"]').click();
      assert.equal(await page.locator('[data-setting="textFontFamily"]').inputValue(),'Tahoma');
      await page.locator('[data-settings-nav="forward"]').click();
      assert.equal(await page.locator('[data-setting="monospaceFontFamily"]').inputValue(),'Courier New');
      await page.locator('[data-settings-action="cancel"]').click();
      assert.equal(await page.evaluate(()=>window.__augitLive.settings.textFontFamily),'Microsoft YaHei UI');
      await page.locator('.titlebar [aria-label="Settings"]').click();
      await page.locator('[data-setting="textFontFamily"]').selectOption('Tahoma');
      await page.locator('[data-settings-action="apply"]').click();
      assert.equal(await page.evaluate(()=>window.__augitLive.settings.textFontFamily),'Tahoma');
      await page.locator('[data-settings-action="cancel"]').click();
      check(`${theme} 设置紧凑面包屑/整栏色带/字体选择和前后导航，草稿跨页保留且取消不保存`,true);
      await page.evaluate(()=>window.__augitOpenDocument('docs/notes.txt'));
      await page.locator('.rail-button[data-tool="commit"]').click();
      await page.locator('.change-file-row').first().dblclick();
      await page.waitForSelector('.editor-content .diff-toolbar [aria-label="Settings"]');
      const order=await page.locator('.editor-content .diff-toolbar button').evaluateAll(nodes=>nodes.map(node=>({label:node.getAttribute('aria-label'),x:node.getBoundingClientRect().x})).filter(item=>['Side-by-side','Unified','Settings'].includes(item.label)));
      assert.deepEqual(order.map(item=>item.label),['Side-by-side','Unified','Settings']);assert.ok(order[2].x>order[1].x);
      await page.locator('.editor-content .diff-toolbar [aria-label="Unified"]').focus();await page.keyboard.press('Tab');
      assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')),'Settings');
      await page.locator('.editor-content .diff-toolbar [aria-label="Settings"]').click();
      assert.equal(await page.locator('.settings-window').count(),0);
      assert.deepEqual(await page.locator('.diff-settings-menu .menu-item').allTextContents(),['Show Whitespaces','Show Line Numbers']);
      const columnsBefore=await page.locator('.diff-columns').evaluate(node=>getComputedStyle(node).gridTemplateColumns);
      await page.locator('[data-diff-display="lineNumbers"]').click();
      assert.equal(await page.locator('.diff-layout').evaluate(node=>node.classList.contains('hide-line-numbers')),true);
      assert.equal(await page.locator('.diff-columns').evaluate(node=>getComputedStyle(node).gridTemplateColumns),columnsBefore);
      await page.locator('.editor-content .diff-toolbar [aria-label="Settings"]').click();await page.locator('[data-diff-display="whitespace"]').click();
      assert.equal(await page.evaluate(()=>window.__augitLive.displayOptions.whitespace),true);
      check(`${theme} Diff齿轮位于单双栏之后且Tab顺序一致，只打开局部只读显示菜单`,true);
      await page.locator('.rail-button[data-tool="history"]').click();
      let date=page.locator('.history-filters > [data-filter-key="date"]');
      if(!await date.isVisible()){await page.locator('[aria-label="More History Filters"]').click();date=page.locator('.history-filter-menu [data-filter-key="date"]');}
      await date.focus();await page.keyboard.press('ArrowDown');await page.locator('[data-history-date="select"]').click();
      await page.locator('[data-history-date-enabled="since"]').check();await page.locator('[data-history-date-field="since"]').fill('2024/02/28');
      await page.locator('[data-history-date-calendar="since"]').click();await page.waitForSelector('.history-calendar');
      assert.equal(await page.locator('.history-calendar [data-calendar-date]').count(),42);
      const calendarBox=await page.locator('.history-calendar').boundingBox(),fieldBox=await page.locator('[data-history-date-field="since"]').boundingBox();
      assert.ok(Math.abs(calendarBox.x-fieldBox.x)<1&&Math.abs(calendarBox.y-fieldBox.y-fieldBox.height-1)<1,JSON.stringify({calendarBox,fieldBox}));
      await page.locator('[data-calendar-date="2024-02-28"]').focus();await page.keyboard.press('ArrowRight');await page.keyboard.press('Enter');
      assert.equal(await page.locator('[data-history-date-field="since"]').inputValue(),'2024/02/29');
      assert.equal(await page.locator('.history-calendar').count(),0);
      assert.equal(await page.locator('.history-date-range-dialog').count(),1);
      await page.locator('[data-history-date-calendar="since"]').click();await page.keyboard.press('Escape');
      assert.equal(await page.locator('.history-date-range-dialog').count(),1);
      await page.locator('[data-history-date-calendar="since"]').click();
      await page.locator('[data-calendar-shift="12"]').focus();await page.keyboard.press('Enter');
      assert.match(await page.locator('.calendar-navigation strong').innerText(),/2025/);
      await page.locator('[data-calendar-none]').focus();await page.keyboard.press('Enter');
      assert.equal(await page.locator('[data-history-date-field="since"]').inputValue(),'');
      assert.equal(await page.locator('[data-history-date-range="confirm"]').isDisabled(),true);
      await page.locator('[data-history-date-field="since"]').fill('2024/02/30');assert.equal(await page.locator('[data-history-date-range="confirm"]').isDisabled(),true);
      await page.keyboard.press('Escape');
      check(`${theme} 自有42格日历支持闰日、键盘提交与Esc只收日历，非法日期阻止确认`,true);
      await page.locator('.rail-button[data-tool="project"]').click();
      const row=page.locator('.side-content.tree [data-tree-path]').last();await row.click({button:'right'});
      const menu=page.locator('.project-menu .context-menu');
      const last=menu.locator('.menu-item').last();await page.keyboard.press('End');
      assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),await last.innerText());
      await page.keyboard.press('Home');assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),await menu.locator('.menu-item').first().innerText());
      const geometry=await menu.evaluate(node=>{const box=node.getBoundingClientRect();return{left:box.left,right:box.right,bottom:box.bottom,width:innerWidth,height:innerHeight};});
      assert.ok(geometry.left>=4&&geometry.right<=geometry.width-4&&geometry.bottom<=geometry.height-4,JSON.stringify(geometry));
      await page.keyboard.press('Escape');assert.deepEqual(scene.errors,[]);
      await row.click({button:'right'});await page.keyboard.press('Home');await page.keyboard.press('Enter');
      await page.waitForFunction(()=>!!window.__augitCopiedPath);
      assert.equal(await page.evaluate(()=>window.__augitCopiedPath),await row.getAttribute('data-tree-path'));
      assert.equal(await menu.count(),0);
      check(`${theme} Project普通菜单按真实尺寸夹边，Home/End键导航真实条目并Esc恢复`,true);
      await page.evaluate(()=>applyTypography({uiSize:40}));
      await row.evaluate(node=>Object.assign(node.style,{position:'fixed',left:`${innerWidth-30}px`,top:`${innerHeight-30}px`,width:'24px',height:'24px',zIndex:'30',overflow:'hidden'}));
      await row.click({button:'right'});
      const corner=await menu.evaluate(node=>{const box=node.getBoundingClientRect();return{left:box.left,right:box.right,bottom:box.bottom,width:box.width,height:innerHeight,viewport:innerWidth};});
      assert.ok(corner.width>=300&&corner.right<=corner.viewport-4&&corner.bottom<=corner.height-4,JSON.stringify(corner));
      await menu.locator('.menu-item').nth(1).evaluate(node=>{node.classList.add('disabled');node.setAttribute('aria-disabled','true');});
      await page.keyboard.press('Home');await page.keyboard.press('ArrowDown');
      assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),await menu.locator('.menu-item').nth(2).innerText());
      await page.keyboard.press('Escape');
      check(`${theme} 40px普通菜单贴右下角仍完整夹边，方向键跳过禁用项`,true);
    }finally{await page.close();}
  }
};
